function getScaleAwareOutlineDefaults(data) {
  const fallbackScale = data.fallbackBox?.scale || [];
  const xs = data.vertices.map((vertex) => vertex[0]);
  const zs = data.vertices.map((vertex) => vertex[1]);
  const footprintSpan = Math.max(
    Number(fallbackScale[0]) || 0,
    Number(fallbackScale[2]) || 0,
    Math.max(...xs) - Math.min(...xs),
    Math.max(...zs) - Math.min(...zs)
  );
  const clamp = (value, minimum, maximum) => Math.max(minimum, Math.min(maximum, value));
  return {
    padding: Number(clamp(0.2 + footprintSpan * 0.004, 0.22, 0.34).toFixed(3)),
    edgeDepth: Number(clamp(0.3 + footprintSpan * 0.002, 0.32, 0.38).toFixed(3)),
  };
}

function createOutline(data, registration = null, registrationMode = "native") {
  const autoDefaults = getScaleAwareOutlineDefaults(data);
  const outline = {
    version: 1,
    mode: "outline",
    source: {
      type: "mipmap-glb-floor",
      registrationMode,
      sourceUpAxis: data.sourceUpAxis || "y",
      confidence: data.confidence,
      metrics: {
        retainedComponentRatio: data.retained,
        dominantFloorAreaRatio: data.area,
        acceptedFloorTriangles: data.triangles,
      },
    },
    vertices: data.vertices.map((vertex) => [...vertex]),
    floorY: data.floorY,
    ceilingY: data.ceilingY,
    fadeWidth: 0.12,
    cameraMotionSmoothing: 0.18,
    cameraMotionAcceleration: 1,
    topCutDepth: 0.25,
    bottomCutDepth: 0.08,
    edgeDepth: { useGlobal: true, global: autoDefaults.edgeDepth },
    padding: { mode: "auto", autoDistance: autoDefaults.padding, distance: autoDefaults.padding },
    cleanup: { mode: "auto", autoMargin: 0.12, margin: 0.12, strength: 1 },
    registration,
    edges: data.vertices.map((_, index) => ({
      id: `edge-${index + 1}`,
      label: `Edge ${index + 1}`,
      enabled: true,
      cutDepth: autoDefaults.edgeDepth,
      depthSlope: 0,
      cleanupMode: "inherit",
      cleanupMargin: 0.12,
      paddingMode: "inherit",
      paddingDistance: autoDefaults.padding,
      cameraActivation: "face",
    })),
  };
  if (Array.isArray(data.levels) && data.levels.length > 1) {
    outline.levels = data.levels.map((level) => ({
      ...createOutline({ ...data, ...level, levels: undefined }, null),
      id: level.id,
      label: level.label,
      source: undefined,
      registration: null,
    }));
    // Keep the vertical bands continuous so stairs and landings between two
    // detected floors are owned by one of the outlines instead of vanishing.
    outline.levels.forEach((level, index) => {
      const nextFloor = outline.levels[index + 1]?.floorY;
      if (Number.isFinite(nextFloor)) level.ceilingY = Math.max(level.ceilingY, nextFloor - 0.0001);
    });
  }
  return outline;
}

function withGeneratedCutaway(sceneId, existingBox = {}) {
  const data = GENERATED_OUTLINE_DATA[sceneId];
  if (!data) return existingBox;
  const usesFullBoundsRectangle = sceneId === "biology-lab" || sceneId === "amphitheater";
  const outlineData = usesFullBoundsRectangle
    ? (() => {
        const [centerX, , centerZ] = data.fallbackBox.position;
        const [width, , depth] = data.fallbackBox.scale;
        return {
          ...data,
          // Biology's disconnected floor tiles and the amphitheater's stepped
          // seating dominate their floor rasters even though both room shells
          // are rectangular. Use the complete GLB horizontal bounds as the
          // editable four-edge starting envelope for these scenes.
          vertices: [
            [centerX - width * 0.5, centerZ + depth * 0.5],
            [centerX - width * 0.5, centerZ - depth * 0.5],
            [centerX + width * 0.5, centerZ - depth * 0.5],
            [centerX + width * 0.5, centerZ + depth * 0.5],
          ],
        };
      })()
    : data;
  return {
    ...structuredClone(data.fallbackBox),
    ...existingBox,
    cutawayMode: existingBox.cutawayMode === "box" ? "box" : "outline",
    // These vertices and height levels were extracted from the GLB and must
    // stay in that coordinate frame. The fallback SOG box has an unrelated
    // 90-degree orientation and non-uniform scale; using it as registration
    // turns walls into floors and stretches the footprint.
    outline: createOutline(
      outlineData,
      null,
      COLLISION_REGISTERED_SCENE_IDS.has(sceneId) ? "collision" : "native"
    ),
  };
}

